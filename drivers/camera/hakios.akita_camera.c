#define SYSREG_PERIC0_PHYS      0x10821000ULL
#define GPIO_PERIC0_PHYS        0x10840000ULL
#define GPP(n)                  ((n) * 0x20)    /* gpp0..gpp15: CON +0, DAT +4, PUD +8, DRV +0xc */

