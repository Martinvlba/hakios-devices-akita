static const struct { uint64_t pa; unsigned pmmu; uint32_t dflt; const struct mmu_stream *s; unsigned n; } mmu_pmmus[] = {
	{ 0x1c110000ULL, 0, 0x6030106, mmu_1c110000_p0, 8 },
	{ 0x1c110000ULL, 1, 0x7030106, mmu_1c110000_p1, 6 },
	{ 0x1c150000ULL, 0, 0x106, NULL, 0 },
	{ 0x1c190000ULL, 0, 0x106, mmu_1c190000_p0, 5 },
};

#define MMU_CTRL_VM             0x8000
#define MMU_ALL_INV_VM          0x8010
#define MMU_FLPT_BASE_VM        0x8404
#define MMU_ATTRIBUTE_VM        0x8408
#define MMU_PMMU_INDICATOR      0x2ffc
#define MMU_STREAM_CFG(n)       (0x2000 + (n) * 0x10)
#define FRONT_IOVA              0x10000000u
#define FRONT_SIDE_IOVA         0x12000000u

static vm_offset_t mmu_flpt;
static vm_offset_t pdma_mem, pdma_scratch;     /* 1 MiB: the queue + the list; 4 MiB of zeros */

/* Android's IOVAs in our table (camera_pdma): its frame and second buffer onto ours, the queue + list at PDMA_IOVA, every
 * other address of the list onto the scratch (4 sections each) */
static void
mmu_map_android(uint64_t frame_pa, unsigned frame_mb, uint64_t side_pa)
{
	uint32_t *t = (uint32_t *)mmu_flpt;
	uint64_t scr = kvtophys(pdma_scratch);

	for (unsigned i = 0; i < sizeof(front_pdma_iovas) / sizeof(front_pdma_iovas[0]); i++) {
		for (unsigned k = 0; k < 4; k++) {
			t[(front_pdma_iovas[i] >> 20) + k] = (uint32_t)((scr + ((uint64_t)k << 20)) >> 4) | 2u;
		}
	}
	for (unsigned i = 0; i < frame_mb; i++) {
		t[(ANDROID_FRAME_IOVA >> 20) + i] = (uint32_t)((frame_pa + ((uint64_t)i << 20)) >> 4) | 2u;
	}
	t[ANDROID_SIDE_IOVA >> 20] = (uint32_t)(side_pa >> 4) | 2u;
	t[PDMA_IOVA >> 20] = (uint32_t)(kvtophys(pdma_mem) >> 4) | 2u;
	flush_dcache(mmu_flpt, 0x40000, FALSE);
	__asm__ volatile ("dsb sy" ::: "memory");
	/* (the SysMMUs were switched on before these entries: their TLBs invalidated again) */
	for (unsigned m = 0; m < 3; m++) {
		static const uint64_t mmus[3] = { 0x1c110000ULL, 0x1c150000ULL, 0x1c190000ULL };

		wr(ml_io_map(mmus[m], 0x10000) + 0x8010, 1);
	}
	__asm__ volatile ("dsb sy" ::: "memory");
}

static bool
ispfe_mmu(bool on, uint64_t frame_pa, unsigned frame_mb, uint64_t side_pa)
{
	static const uint64_t mmus[3] = { 0x1c110000ULL, 0x1c150000ULL, 0x1c190000ULL };

	if (on) {
		uint32_t *t;

		if (!mmu_flpt && kmem_alloc_contig(kernel_map, &mmu_flpt, 0x40000, 0x3ffff, 0, 0, KMA_KOBJECT | KMA_DATA,
		    VM_KERN_MEMORY_IOKIT) != KERN_SUCCESS) {
			mmu_flpt = 0;
			printf("akita camera: capture: no memory for the SysMMU table\n");
			return false;
		}
		t = (uint32_t *)mmu_flpt;
		memset(t, 0, 0x40000);
		for (unsigned i = 0; i < frame_mb; i++) {
			t[(FRONT_IOVA >> 20) + i] = (uint32_t)((frame_pa + ((uint64_t)i << 20)) >> 4) | 2u;
		}
		t[FRONT_SIDE_IOVA >> 20] = (uint32_t)(side_pa >> 4) | 2u;
		flush_dcache(mmu_flpt, 0x40000, FALSE);
		__asm__ volatile ("dsb sy" ::: "memory");
	}
	for (unsigned m = 0; m < 3; m++) {
		vm_offset_t r = ml_io_map(mmus[m], 0x10000);

		if (on) {
			for (unsigned k = 0; k < sizeof(mmu_pmmus) / sizeof(mmu_pmmus[0]); k++) {
				if (mmu_pmmus[k].pa != mmus[m]) {
					continue;
				}
				wr(r + MMU_PMMU_INDICATOR, mmu_pmmus[k].pmmu & 0xf);
				(void)rd(r + MMU_PMMU_INDICATOR);
				if (mmu_pmmus[k].dflt != ~0u) {
					wr(r + MMU_STREAM_CFG(0), mmu_pmmus[k].dflt & 0xffff017fu);
				}
				for (unsigned e = 0; e < mmu_pmmus[k].n; e++) {
					const struct mmu_stream *st = &mmu_pmmus[k].s[e];

					wr(r + MMU_STREAM_CFG(st->index), st->cfg & 0xffff017fu);
					wr(r + MMU_STREAM_CFG(st->index) + 4, st->match & 0x301u);
					wr(r + MMU_STREAM_CFG(st->index) + 8, st->value);
					wr(r + MMU_STREAM_CFG(st->index) + 0xc, st->mask);
				}
			}
			wr(r + MMU_FLPT_BASE_VM, (uint32_t)(kvtophys(mmu_flpt) >> 12));
			wr(r + MMU_ATTRIBUTE_VM, (rd(r + MMU_ATTRIBUTE_VM) & ~0xf0000u & ~(0xfu << 7)) | 0x20000u | (1u << 11) | (0xfu << 7));
			wr(r + MMU_CTRL_VM, rd(r + MMU_CTRL_VM) | 1u);
			wr(r + MMU_ALL_INV_VM, 1);
		} else {
			wr(r + MMU_CTRL_VM, rd(r + MMU_CTRL_VM) & ~1u);
			wr(r + MMU_FLPT_BASE_VM, 0);
			wr(r + MMU_ALL_INV_VM, 1);
		}
		printf("akita camera: capture: SysMMU %#llx %s: CTRL_VM %#x FLPT %#x ATTR %#x STATUS %#x\n", mmus[m], on ? "on" : "off",
		    rd(r + MMU_CTRL_VM), rd(r + MMU_FLPT_BASE_VM), rd(r + MMU_ATTRIBUTE_VM), rd(r + 0x8));
	}
	return true;
}


static void
front_capture(void)
{
	const struct sensor *c = &sensors[1];
	vm_offset_t fe = 0, csis = 0, frame = 0, side = 0, sysreg = 0, pmu = ml_io_map(0x15462000ULL, 0x2000);
	uint64_t frame_pa, side_pa;
	uint8_t one = 1, zero = 0, fc = 0;
	unsigned changed = 0, first = ~0u;
	unsigned on = 0, use_pdma = 1, ch0_on = 1, arm37 = 0, phy_late = 1;
	uint32_t old_fe_mux = 0, old_fe_div = 0;
	bool fe_clk_set = false;
	bool mmu_used = false;

	if (!(rd(pmu + 0x484) & 1u)) {
		printf("akita camera: capture: pd-ispfe is off: not trying\n");
		return;
	}
	/* (1 MiB aligned, whole MiBs: the SysMMU maps them with 1 MiB sections) */
	if (kmem_alloc_contig(kernel_map, &frame, FRONT_BUF_MB << 20, 0xfffff, 0, 0, KMA_KOBJECT | KMA_DATA, VM_KERN_MEMORY_IOKIT) != KERN_SUCCESS ||
	    kmem_alloc_contig(kernel_map, &side, FRONT_SIDE, 0xfffff, 0, 0, KMA_KOBJECT | KMA_DATA, VM_KERN_MEMORY_IOKIT) != KERN_SUCCESS) {
		printf("akita camera: capture: no contiguous memory for the frame\n");
		return;
	}
	frame_pa = kvtophys(frame);
	side_pa = kvtophys(side);
	memset((void *)frame, 0xa5, FRONT_BUF);
	memset((void *)side, 0xa5, FRONT_SIDE);
	flush_dcache(frame, FRONT_BUF, FALSE);
	flush_dcache(side, FRONT_SIDE, FALSE);
	printf("akita camera: capture: frame buffer %#llx (%u bytes), second buffer %#llx\n", frame_pa, FRONT_BUF, side_pa);
	fe = ml_io_map(ISPFE_FE_PHYS, 0x100000);
	csis = ml_io_map(ISPFE_CSIS_PHYS, 0xd0000);

	/* pd-ispfe off and on again, for the block to start from its reset as on Android (which powers it down whenever no
	 * camera is open; here it is on from the boot): CMU_ISPFE's registers kept and put back as pmucal's ispfe_save does,
	 * TZPC saved and restored by the SMCs exynos-pd uses. camera_pdcycle=0: not done */
	{
		unsigned cyc = 1;

		PE_parse_boot_argn("camera_pdcycle", &cyc, sizeof(cyc));
		if (cyc) {
			vm_offset_t cmu = ml_io_map(CMU_ISPFE_PHYS, 0x4000);
			static uint32_t keep[sizeof(cmu_ispfe_regs) / sizeof(cmu_ispfe_regs[0])];
			uint32_t st = 1;

			for (unsigned i = 0; i < sizeof(cmu_ispfe_regs) / sizeof(cmu_ispfe_regs[0]); i++) {
				keep[i] = rd(cmu + cmu_ispfe_regs[i]);
			}
			cam_smc(SMC_PREPARE_PD_ONOFF, PD_GET_IN_DOWN, ISPFE_SMC_ID, PD_TZPC_GROUP);
			cam_smc(SMC_PRIV_REG, 0x15462480ULL, PRIV_REG_WRITE, rd(pmu + 0x480) & ~1u);
			for (int i = 0; i < 1000 && (st & 1u); i++) {
				delay(10);
				st = rd(pmu + 0x484);
			}
			printf("akita camera: capture: pd-ispfe off (status %#x)\n", st);
			delay(1000);
			cam_smc(SMC_PRIV_REG, 0x15462480ULL, PRIV_REG_WRITE, rd(pmu + 0x480) | 1u);
			for (int i = 0; i < 1000 && !(st & 1u); i++) {
				delay(10);
				st = rd(pmu + 0x484);
			}
			cam_smc(SMC_PREPARE_PD_ONOFF, PD_WAKEUP_DOWN, ISPFE_SMC_ID, PD_TZPC_GROUP);
			printf("akita camera: capture: pd-ispfe on again (status %#x); CMU_ISPFE 0x600 %#x 0x1800 %#x after the reset\n", st,
			    rd(cmu + 0x600), rd(cmu + 0x1800));
			for (unsigned i = 0; i < sizeof(cmu_ispfe_regs) / sizeof(cmu_ispfe_regs[0]); i++) {
				if (rd(cmu + cmu_ispfe_regs[i]) != keep[i]) {
					wr(cmu + cmu_ispfe_regs[i], keep[i]);
				}
			}
			if (!(st & 1u)) {
				printf("akita camera: capture: pd-ispfe did not come back: not trying\n");
				return;
			}
		}
	}
	/* the front camera powered and set to its mode (not streaming) */
	if (!i2c_bus_up(c->bus)) {
		return;
	}
	for (on = 0; on < 4 && c->ldo[on] != 0; on++) {
		if (!slg_ldo_on(c->ldo[on], c->mv[on])) {
			goto down;
		}
	}
	delay(1000);
	pin_out(c->reset_bank, c->reset_pin, true);
	mclk(c->clk, c->clk_bank, c->clk_pin, true);
	delay(10000);
	if (!imx712_mode(c)) {
		goto down;
	}
	/* ISPFE's TZPC restored, as Linux's exynos-pd does after each power-on of pd-ispfe (exynos-pd_el3: SMC 0x82000410
	 * (PD_WAKEUP_DOWN, ISPFE, TZPC group)): pd-ispfe is on from the boot here and nobody made that call. camera_tzpc=0: no */
	{
		unsigned tzpc = 1;

		PE_parse_boot_argn("camera_tzpc", &tzpc, sizeof(tzpc));
		if (tzpc) {
			uint64_t r = cam_smc(SMC_PREPARE_PD_ONOFF, PD_WAKEUP_DOWN, ISPFE_SMC_ID, PD_TZPC_GROUP);

			printf("akita camera: capture: ISPFE TZPC restore SMC: %#llx\n", r);
		}
	}
	/* the D-PHYs out of isolation, as Linux's phy-exynos-mipi power_on does (exynos_pmu_update: here the PRIV_REG SMC);
	 * Android 11-17: 1 while a camera streams, 0 when closed -- camera=7 before this left it 0 and no bytes came */
	{
		uint64_t r = cam_smc(SMC_PRIV_REG, PMU_CSI_PHY_ISO, PRIV_REG_WRITE, rd(pmu + 0x1ebc) | 1u);

		printf("akita camera: capture: CSI PHY isolation bypass: %#x (SMC %#llx)\n", rd(pmu + 0x1ebc), r);
	}
	/* ... and D-PHYs 5 and 6 (0x1c103100: the clock lane and 4 data lanes; 0x1c103600) out of reset: SYSREG_ISPFE +0x500
	 * (device tree system-controller@1C020500 "samsung,exynos-csis", each dcphy node's "reset" = its bit). Android 11-17:
	 * 0x60 while the front camera streams, 0x2 for the main one (D-PHY 1) */
	sysreg = ml_io_map(ISPFE_SYSREG_PHYS, 0x1000);
	PE_parse_boot_argn("camera_phyorder", &phy_late, sizeof(phy_late));
	if (!phy_late) {
		wr(sysreg + 0x500, rd(sysreg + 0x500) | FRONT_DPHY_RESET_BITS);
		printf("akita camera: capture: D-PHY reset release: %#x\n", rd(sysreg + 0x500));
	}
	/* SYSREG_ISPFE 0x104 BUS_COMPONENT_DRCG_EN, 0x108 MEMCLK: what pmucal saves and restores across pd-ispfe's power
	 * cycles (flexpmu_cal_local_zuma.h ispfe_save); Android while a camera streams: 0x3ffffff, 0 */
	/* the front end's clock (CMU_TOP MUX/DIV_CLKCMU_ISPFE_NOC): Android, a camera streaming, mux 4 (PLL_SHARED1_D4) div 1;
	 * ours from the boot mux 1 (PLL_SHARED3_D1) div 5 -- the front end at a fraction of its speed. camera_feclk=0: left */
	{
		unsigned feclk = 1;

		PE_parse_boot_argn("camera_feclk", &feclk, sizeof(feclk));
		old_fe_mux = rd(cmu_top + CMU_TOP_ISPFE_MUX);
		old_fe_div = rd(cmu_top + CMU_TOP_ISPFE_DIV);
		if (feclk) {
			wr(cmu_top + CMU_TOP_ISPFE_DIV, (old_fe_div & ~0x1fu) | 1u);
			for (int i = 0; i < 1000 && (rd(cmu_top + CMU_TOP_ISPFE_DIV) & (1u << 16)); i++) {
				delay(1);
			}
			wr(cmu_top + CMU_TOP_ISPFE_MUX, (old_fe_mux & ~7u) | 4u);
			for (int i = 0; i < 1000 && (rd(cmu_top + CMU_TOP_ISPFE_MUX) & (1u << 16)); i++) {
				delay(1);
			}
			fe_clk_set = true;
		}
		printf("akita camera: capture: ISPFE_NOC clock: mux %#x div %#x (was %#x %#x)\n", rd(cmu_top + CMU_TOP_ISPFE_MUX),
		    rd(cmu_top + CMU_TOP_ISPFE_DIV), old_fe_mux, old_fe_div);
	}
	printf("akita camera: capture: SYSREG_ISPFE DRCG_EN %#x MEMCLK %#x\n", rd(sysreg + 0x104), rd(sysreg + 0x108));
	{
		/* the NoC's ends of ISPFE's four AXI links (CMU_NOCL2AA 0x26c00000: gates of LH_AXI_MI_D0..D3_ISPFE, their
		 * Q-channels; pd-nocl2aa is on: the display's traffic goes through it too) */
		vm_offset_t n2 = ml_io_map(0x26c00000ULL, 0x4000);

		printf("akita camera: capture: NOCL2AA ISPFE links: gates %#x %#x %#x %#x QCH %#x %#x %#x %#x\n", rd(n2 + 0x2070),
		    rd(n2 + 0x2080), rd(n2 + 0x208c), rd(n2 + 0x2094), rd(n2 + 0x30ac), rd(n2 + 0x30bc), rd(n2 + 0x30c8), rd(n2 + 0x30d0));
	}
	{
		unsigned drcg = 1;

		PE_parse_boot_argn("camera_drcg", &drcg, sizeof(drcg));
		if (drcg) {
			wr(sysreg + 0x104, 0x3ffffff);
			wr(sysreg + 0x108, 0);
			printf("akita camera: capture: SYSREG_ISPFE now DRCG_EN %#x MEMCLK %#x\n", rd(sysreg + 0x104), rd(sysreg + 0x108));
		}
	}
	PE_parse_boot_argn("camera_arm37", &arm37, sizeof(arm37));
	{
		unsigned pre = 1;       /* camera_blkstop=0: not done. Android's flip (11-18 kpblk-flip-front.txt) stops and clears
		                         * block 0 before setting it up: +0x18 0, +0x1c 0, 0x200a4 1 (stop), +0x10 0, +0x30 9, +0x44
		                         * 0x10, +0x58 0, 0x37028 0, then +0x30 1, +0x30 0, +0x44 0 */

		PE_parse_boot_argn("camera_blkstop", &pre, sizeof(pre));
		if (pre) {
			wr(fe + 0x20418, 0);
			wr(fe + 0x2041c, 0);
			wr(fe + 0x200a4, 1);
			wr(fe + 0x20410, 0);
			wr(fe + 0x20430, 9);
			wr(fe + 0x20444, 0x10);
			wr(fe + 0x20458, 0);
			wr(fe + 0x37028, 0);
			delay(600);
			wr(fe + 0x20430, 1);
			wr(fe + 0x20430, 0);
			wr(fe + 0x20444, 0);
			printf("akita camera: capture: block 0 stopped and cleared first (0x200a4 now %#x)\n", rd(fe + 0x200a4));
		}
	}
	/* Android's setup of the PHY, CSIS link 6 and the front end */
	for (unsigned i = 0; i < sizeof(ispfe_front_setup) / sizeof(ispfe_front_setup[0]); i++) {
		const struct ispfe_write *w = &ispfe_front_setup[i];
		vm_offset_t va = w->pa >= ISPFE_FE_PHYS ? fe + (w->pa - ISPFE_FE_PHYS) : csis + (w->pa - ISPFE_CSIS_PHYS);

		if (w->delay_us) {
			delay(w->delay_us);
		}
		if (w->pa == 0x1c337300 && !arm37) {
			continue;       /* camera_arm37=0 (default): the 0x37 block not armed before the first frame (Android 11-18:
			                 * +0x37300 0 at the first frame start; armed with 4 only after each frame's end) */
		}
		wr(va, w->val);
	}
	{
		unsigned c5000c = 0xc31;        /* fe +0x5000c: Android 0xc31 while streaming, the setup writes 0xc11 */

		PE_parse_boot_argn("camera_5000c", &c5000c, sizeof(c5000c));
		if (c5000c != 0xffffffffu) {
			wr(fe + 0x5000c, c5000c);
			printf("akita camera: capture: fe +0x5000c = %#x (read %#x)\n", c5000c, rd(fe + 0x5000c));
		}
	}
	{
		unsigned c700 = 0xffffffffu;    /* CSIS link 6 +0x700: Android 0xf1 (a status: reads back 0xf2, then 0) */

		PE_parse_boot_argn("camera_c700", &c700, sizeof(c700));
		if (c700 != 0xffffffffu) {
			wr(csis + 0x60700, c700);
			printf("akita camera: capture: CSIS link 6 +0x700 = %#x (read %#x)\n", c700, rd(csis + 0x60700));
		}
	}
	{
		unsigned dt = 0;        /* camera_csiscfg=V: CSIS link 6 channel 0's ISP_CONFIG (+0x40, Android 0x30ac = RAW10) overridden
		                         * (a test: 0x30a8 = RAW8 -- no line of the sensor's then matches, only frame start/end pass) */

		if (PE_parse_boot_argn("camera_csiscfg", &dt, sizeof(dt)) && dt) {
			wr(csis + 0x60040, dt);
			printf("akita camera: capture: CSIS link 6 +0x40 = %#x\n", rd(csis + 0x60040));
		}
	}
	if (phy_late) {
		/* (Android 11-17 ultra-wide trace: the lanes configured and enabled, CSIS set up, and only then the D-PHYs'
		 * resets released -- the other way round the lanes never calibrated: +0xc0.. 0xffff, no deskew results) */
		wr(sysreg + 0x500, rd(sysreg + 0x500) | FRONT_DPHY_RESET_BITS);
		printf("akita camera: capture: D-PHY reset release after the PHY's setup: %#x\n", rd(sysreg + 0x500));
	}
	printf("akita camera: capture: the PHY, CSIS link 6 and the front end set up (%u writes)\n",
	    (unsigned)(sizeof(ispfe_front_setup) / sizeof(ispfe_front_setup[0])));
	PE_parse_boot_argn("camera_ch0", &ch0_on, sizeof(ch0_on));

	/* the frame's channel and the 0x37 block, as the PDMA's list would, with our buffers */
	wr(fe + 0x20554, FRONT_STRIDE);
	wr(fe + 0x20550, 4);
	wr(fe + 0x20544, 0);
	wr(fe + 0x20540, 1);
	{
		unsigned use_mmu = 1;
		uint64_t fa = frame_pa, sa = side_pa;

		PE_parse_boot_argn("camera_mmu", &use_mmu, sizeof(use_mmu));
		if (use_mmu && ispfe_mmu(true, frame_pa, FRONT_BUF_MB, side_pa)) {
			mmu_used = true;
			fa = FRONT_IOVA;
			sa = FRONT_SIDE_IOVA;
		}
		PE_parse_boot_argn("camera_pdma", &use_pdma, sizeof(use_pdma));
		if (!mmu_used) {
			use_pdma = 0;
		}
		if (use_pdma && ((!pdma_mem && kmem_alloc_contig(kernel_map, &pdma_mem, 0x100000, 0xfffff, 0, 0, KMA_KOBJECT | KMA_DATA,
		    VM_KERN_MEMORY_IOKIT) != KERN_SUCCESS) || (!pdma_scratch && kmem_alloc_contig(kernel_map, &pdma_scratch, 0x400000,
		    0xfffff, 0, 0, KMA_KOBJECT | KMA_DATA, VM_KERN_MEMORY_IOKIT) != KERN_SUCCESS))) {
			printf("akita camera: capture: no memory for the PDMA\n");
			use_pdma = 0;
		}
		if (use_pdma) {
			uint32_t *q = (uint32_t *)pdma_mem;

			memset((void *)pdma_mem, 0, 0x100000);
			memset((void *)pdma_scratch, 0, 0x400000);
			for (unsigned e = 0; e < 256; e++) {
				q[e * 4] = 0xc003;
				q[e * 4 + 1] = PDMA_IOVA + 0x1000;
				q[e * 4 + 2] = 0;
				q[e * 4 + 3] = sizeof(front_pdma_list);
			}
			memcpy((void *)(pdma_mem + 0x1000), front_pdma_list, sizeof(front_pdma_list));
			flush_dcache(pdma_mem, 0x100000, FALSE);
			flush_dcache(pdma_scratch, 0x400000, FALSE);
			mmu_map_android(frame_pa, FRONT_BUF_MB, side_pa);
			/* Android's start of the PDMA (11-17 trace), less the queue's first entry (just before stream on) */
			wr(fe + 0x9002c, 1);
			wr(fe + 0x90040, 0x1f);
			for (unsigned k = 0; k < 5; k++) {
				wr(fe + 0x90020 + k * 0x1000, 0);
				wr(fe + 0x90034 + k * 0x1000, 0);
			}
			wr(fe + 0x90004, PDMA_IOVA);
			wr(fe + 0x90008, 0);
			wr(fe + 0x9000c, 0x3e8);
			wr(fe + 0x90010, 0);
			wr(fe + 0x90000, 1);
			wr(fe + 0x90028, 1);
			printf("akita camera: capture: PDMA on: queue at %#x, Android's list (%u bytes), its %u buffer addresses mapped\n",
			    PDMA_IOVA, (unsigned)sizeof(front_pdma_list), (unsigned)(sizeof(front_pdma_iovas) / sizeof(front_pdma_iovas[0])));
		}
		wr(fe + 0x205c0, (uint32_t)fa);
		wr(fe + 0x205c4, (uint32_t)(fa >> 32));
		wr(fe + 0x20508, 0x71);
		wr(fe + 0x2050c, 0);
		wr(fe + 0x20510, (uint32_t)sa);
		wr(fe + 0x20514, (uint32_t)(sa >> 32));
	}
	{
		unsigned b37 = 1;       /* camera_37=0: the 0x37 block's per-frame words not written (Android's first frame runs
		                         * with +0x37028 0 and +0x37500 0: the block off) */

		PE_parse_boot_argn("camera_37", &b37, sizeof(b37));
		if (b37) {
			for (unsigned i = 0; i < sizeof(ispfe_front_37) / sizeof(ispfe_front_37[0]); i++) {
				wr(fe + ispfe_front_37[i].off, ispfe_front_37[i].val);
			}
		} else {
			wr(fe + 0x37028, 0);
			wr(fe + 0x37500, 0);
			printf("akita camera: capture: the 0x37 block left off (+0x37028 %#x)\n", rd(fe + 0x37028));
		}
	}
	{
		unsigned proc = 1;

		PE_parse_boot_argn("camera_proc", &proc, sizeof(proc));
		if (proc) {
			for (unsigned i = 0; i < sizeof(ispfe_front_proc) / sizeof(ispfe_front_proc[0]); i++) {
				wr(fe + ispfe_front_proc[i].off, ispfe_front_proc[i].val);
			}
			if (use_pdma) {         /* Android's IOVAs are mapped (onto scratch): its 9 buffer addresses written too */
				static const uint32_t a9[][2] = { { 0x54a84, 0xef660000 }, { 0x54ecc, 0xe8c00000 }, { 0x55178, 0xfd880000 },
					{ 0x55198, 0xe5ef4000 }, { 0x551b0, 0xef660000 }, { 0x551c0, 0xeb930000 }, { 0x551c8, 0xeb900000 },
					{ 0x551e0, 0xf6c00000 }, { 0x55200, 0xe8c00000 } };

				for (unsigned i = 0; i < 9; i++) {
					wr(fe + a9[i][0], a9[i][1]);
				}
			}
			printf("akita camera: capture: the processing blocks' %u words written\n",
			    (unsigned)(sizeof(ispfe_front_proc) / sizeof(ispfe_front_proc[0])));
		}
	}
	if (!ch0_on) {          /* camera_ch0=0: no output at all (channel 0 off, the 0x37 block not armed, no PDMA) */
		wr(fe + 0x20540, 0);
		wr(fe + 0x37300, 0);
		use_pdma = 0;
		printf("akita camera: capture: channel 0 and the 0x37 block left off\n");
	}
	/* the isp-fe S2MPUs (stage-2 protection, programmed on Android by pKVM only) protection off for every VID, as the
	 * GPU's needed (hakios.akita_mali.c mali_s2mpu=2: found on there, with a table letting a fifth of the pages through,
	 * and refusing silently) -- only the registers Google's v9 code touches */
	for (unsigned i = 0; i < 3; i++) {
		static const uint64_t s2mpu_pa[3] = { 0x1c140000ULL, 0x1c180000ULL, 0x1c1c0000ULL };
		vm_offset_t s2 = ml_io_map(s2mpu_pa[i], 0x3000);

		wr(s2 + 0x54, 0xff);            /* CTRL_PROT_EN_PER_VID_CLR */
		wr(s2 + 0x1000, 1);             /* ALL_INVALIDATION */
		__asm__ volatile ("dsb sy" ::: "memory");
	}
	delay(100);
	printf("akita camera: capture: isp-fe S2MPUs: protection off for every VID\n");
	{
		unsigned arm = 1;

		PE_parse_boot_argn("camera_arm", &arm, sizeof(arm));
		if (arm && ch0_on && arm37) {      /* Android's re-arm of the front's block after each frame: 0x500e8 3, then 0x37300 4 */
			wr(fe + 0x500e8, 3);
			wr(fe + 0x37300, 4);
		}
	}
	{
		unsigned sz = 0;        /* camera_size=0xHHHHWWWW: block 0's and the 0x37 block's frame size overridden (a test) */

		if (PE_parse_boot_argn("camera_size", &sz, sizeof(sz)) && sz) {
			wr(fe + 0x20474, sz);
			wr(fe + 0x37904, sz);
			printf("akita camera: capture: frame size set to %#x (block 0 %#x, 0x37 block %#x)\n", sz, rd(fe + 0x20474),
			    rd(fe + 0x37904));
		}
	}
	{
		/* camera_z1..camera_z4=OFF: front-end words set to 0 after the setup (a test of which of block 0's output/route
		 * words make it refuse its frames: +0x60/64/6c/70, +0xc8/cc/d0, +0xd4/d8 ...) */
		static const char *zn[4] = { "camera_z1", "camera_z2", "camera_z3", "camera_z4" };

		for (unsigned k = 0; k < 4; k++) {
			unsigned off = 0;

			if (PE_parse_boot_argn(zn[k], &off, sizeof(off)) && off >= 0x20000 && off < 0x60000) {
				wr(fe + off, 0);
				printf("akita camera: capture: fe +%#x = 0 (read %#x)\n", off, rd(fe + off));
			}
		}
	}
	{
		unsigned b0 = 0xffffffffu;      /* camera_200b0=V: fe +0x200b0 (Android 1: per-frame configuration by the PDMA?) */

		if (PE_parse_boot_argn("camera_200b0", &b0, sizeof(b0)) && b0 != 0xffffffffu) {
			wr(fe + 0x200b0, b0);
			printf("akita camera: capture: fe +0x200b0 = %#x\n", rd(fe + 0x200b0));
		}
	}
	if (use_pdma) {
		wr(fe + 0x90010, 0x10);
	}
	printf("akita camera: capture: channel 0 -> %#llx; stream on\n", frame_pa);
	{
		unsigned pre = 100;     /* camera_prestream=N ms between the receiver's setup and the stream (Android: 141 ms) */

		PE_parse_boot_argn("camera_prestream", &pre, sizeof(pre));
		if (pre) {
			delay_for_interval(pre, NSEC_PER_MSEC);
		}
		/* the D-PHYs' state words before the stream (Android, a working stream: clock lane +0x1e0.. 1 1 0xe 0x11, an idle
		 * PHY 1 1 0xe 0x40; ours while streaming: 0x20 2 0xd 0x1f) */
		printf("akita camera: capture: before the stream: CIS_CLK1 mux %#x div %#x gate %#x DFTMUX(0x3008) %#x (Android 0 0 0x200000 2); "
		    "0x3004 %#x 0x300c %#x\n", rd(cmu_top + 0x1014), rd(cmu_top + 0x1814), rd(cmu_top + 0x203c), rd(cmu_top + 0x3008),
		    rd(cmu_top + 0x3004), rd(cmu_top + 0x300c));
		printf("akita camera: capture: before the stream: D-PHY 5 clock +1e0: %x %x %x %x; lane 0 +c0: %x %x +e0: %x %x %x %x; "
		    "D-PHY 6 +6e0: %x %x %x %x\n", rd(csis + 0xc31e0), rd(csis + 0xc31e4), rd(csis + 0xc31e8), rd(csis + 0xc31ec),
		    rd(csis + 0xc32c0), rd(csis + 0xc32c4), rd(csis + 0xc32e0), rd(csis + 0xc32e4), rd(csis + 0xc32e8),
		    rd(csis + 0xc32ec), rd(csis + 0xc36e0), rd(csis + 0xc36e4), rd(csis + 0xc36e8), rd(csis + 0xc36ec));
	}
	{
		unsigned first = 0;    /* camera_startfirst=N: the front end started N ms BEFORE the stream (Android's front flip
		                         * 11-18: start, then 68 ms to the first frame); 0: 34 us after it, as the 11-17 trace */

		PE_parse_boot_argn("camera_startfirst", &first, sizeof(first));
		if (first) {
			wr(fe + 0x200a0, 1);
			delay_for_interval(first, NSEC_PER_MSEC);
			i2c_write16(c->bus, 0x1a, 0x0100, &one, 1);
		} else {
			i2c_write16(c->bus, 0x1a, 0x0100, &one, 1);
			wr(fe + 0x200a0, 1);
		}
	}
	/* 300 ms of the front end's status, every 1 ms, each change said; Android's interrupt handler mirrored (11-17 trace:
	 * it reads 0x20110/0x20114/0x2043c/0x2044c/0x20450, then writes 0x2008c 1, 0x20404 0, 0x20424 1 or 0x1a, 0x20438 0,
	 * 0x2044c 0, 0x20110 0; after the 0x1a kind the next frame armed: 0x5xxxx, 0x3x300 0, 0x37300 4). camera_irq=0: only
	 * watch */
	{
		static const uint32_t st[] = { 0x2008c, 0x20110, 0x20114, 0x20404, 0x20420, 0x20424, 0x20428, 0x20438, 0x2043c,
			0x2044c, 0x20450, 0x204ac, 0x204a0, 0x204bc, 0x204c0, 0x500e8, 0x500ec, 0x50118, 0x5011c, 0x501ac, 0x37300,
			0x37304, 0x50000, 0x5000c, 0x50014, 0x5001c, 0x20540, 0x20508, 0x90010, 0x90014, 0x90028, 0x20708 };
		uint32_t last[sizeof(st) / sizeof(st[0])] = { 0 };
		unsigned handle = 1, said = 0, handled = 0, w1c_err = 1, csis_said = 0, en18 = 0;

		PE_parse_boot_argn("camera_irq", &handle, sizeof(handle));
		PE_parse_boot_argn("camera_w1c", &w1c_err, sizeof(w1c_err));
		PE_parse_boot_argn("camera_en18", &en18, sizeof(en18));
		for (unsigned ms = 0; ms < 300; ms++) {
			uint32_t v[sizeof(st) / sizeof(st[0])];
			bool ch = false;

			for (unsigned k = 0; k < sizeof(st) / sizeof(st[0]); k++) {
				v[k] = rd(fe + st[k]);
				ch |= v[k] != last[k] || ms == 0;
			}
			if (ch && said < 60) {
				char line[640];
				int n = snprintf(line, sizeof(line), "%3u ms:", ms);

				for (unsigned k = 0; k < sizeof(st) / sizeof(st[0]); k++) {
					n += snprintf(line + n, sizeof(line) - (size_t)n, " %x:%x", st[k], v[k]);
				}
				printf("akita camera: capture: fe status %s\n", line);
				said++;
			}
			if ((v[5] & 1u) && !(last[5] & 1u) && csis_said < 2) {
				/* CSIS link 6 +0x00..+0xfc at a frame start (Android's: kpcsis-flip-front.txt) */
				char cl[700];
				int cn = 0;

				for (uint32_t o = 0; o < 0x100; o += 4) {
					uint32_t x = rd(csis + 0x60000 + o);

					if (x && x != 0xdeadcafe && x != 0x80008000 && (x & 0xffff) != 0x00fc) {
						cn += snprintf(cl + cn, sizeof(cl) - (size_t)cn, " %x:%x", o, x);
					}
				}
				printf("akita camera: capture: at frame start %u ms: CSIS link 6:%s\n", ms, cl);
				csis_said++;
			}
			if (en18 && ms == en18) {
				wr(fe + 0x20418, 1);    /* camera_en18=N: block 0's +0x18 (its enable) set N ms after stream-on */
				printf("akita camera: capture: block 0 +0x18 = 1 at %u ms\n", ms);
			}
			memcpy(last, v, sizeof(last));
			if (use_pdma && (v[5] & 1u)) {
				wr(fe + 0x90010, (rd(fe + 0x90010) + 0x10) & 0xff0u);
			}
			if (handle && (v[0] | v[1] | v[2] | v[8] | v[9] | v[10])) {
				wr(fe + 0x2008c, 1);
				wr(fe + 0x20404, 0);
				wr(fe + 0x20424, v[5] | (v[6] ? 0x1au : 0));
				wr(fe + 0x20438, w1c_err ? v[7] : 0);      /* camera_w1c=1: the error word written back (W1C?) */
				if (w1c_err) {
					wr(fe + 0x204ac, v[11]);
				}
				wr(fe + 0x2044c, 0);
				wr(fe + 0x20110, 0);
				if ((v[5] & 0x1a) || v[6]) {
					static const uint32_t z[] = { 0x50058, 0x50088, 0x500b8, 0x50118, 0x501ac, 0x31300, 0x33300,
						0x35300, 0x39300, 0x3b300, 0x3c300, 0x3d300, 0x3e300 };

					for (unsigned k = 0; k < sizeof(z) / sizeof(z[0]); k++) {
						wr(fe + z[k], 0);
					}
					wr(fe + 0x500e8, 3);
					wr(fe + 0x37300, 4);
				}
				handled++;
			}
			delay(1000);
		}
		printf("akita camera: capture: fe events handled: %u\n", handled);
	}
	{
		/* the sensor's registers while it streams, as Android's (imx712-front-regs-android.txt, i2ctransfer 16-byte bursts):
		 * the lines that are not all 0. camera_sdump=0: not said */
		static const uint16_t rr[][2] = { { 0x0000, 0x1000 }, { 0x3000, 0x3200 }, { 0x4000, 0x4a00 }, { 0x5000, 0x5100 },
			{ 0x6a00, 0x6b00 }, { 0x7000, 0x7100 } };
		unsigned sd = 1;

		PE_parse_boot_argn("camera_sdump", &sd, sizeof(sd));
		for (unsigned k = 0; sd && k < sizeof(rr) / sizeof(rr[0]); k++) {
			for (unsigned a = rr[k][0]; a < rr[k][1]; a += 16) {
				uint8_t b[16] = { 0 };
				bool nz = false;

				if (!i2c_read16(c->bus, 0x1a, (uint16_t)a, b, 16)) {
					continue;
				}
				for (int q = 0; q < 16; q++) {
					nz |= b[q] != 0;
				}
				if (nz) {
					printf("akita camera: sensor %04x: %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x\n",
					    a, b[0], b[1], b[2], b[3], b[4], b[5], b[6], b[7], b[8], b[9], b[10], b[11], b[12], b[13], b[14], b[15]);
				}
			}
		}
	}
	{
		unsigned dump = 1;

		PE_parse_boot_argn("camera_dump", &dump, sizeof(dump));
		if (dump) {
			char line[240];
			int n = 0;

			/* the PHY block (0x1c100000.., 0x1c101000.., D-PHYs 5/6 0x1c103000..0x1c103fff; Android 11-18 more-front.txt) */
			{
				static const uint32_t r[][2] = { { 0x1c100000, 0x1000 }, { 0x1c101000, 0x2000 }, { 0x1c103000, 0x1000 },
					{ 0x1c104000, 0x1000 } };

				for (unsigned k = 0; k < sizeof(r) / sizeof(r[0]); k++) {
					for (uint32_t o = 0; o < r[k][1]; o += 4) {
						uint32_t v = rd(csis + (r[k][0] - ISPFE_CSIS_PHYS) + o);

						if (v && v != 0xdeadcafe && v != 0xfa11fa11) {
							n += snprintf(line + n, sizeof(line) - (size_t)n, " %x:%x", r[k][0] + o, v);
						}
						if (n > 200) {
							printf("akita camera: capture: PHY:%s\n", line);
							n = 0;
						}
					}
				}
				if (n) {
					printf("akita camera: capture: PHY:%s\n", line);
					n = 0;
				}
			}
			/* CSIS link 6 +0x100..0xfff (Android, front streaming: +0x240.. the channels' active config, +0x500/0x504
			 * frame counters 0x1d2, +0x700 0xf1); the words that are neither 0 nor 0xdeadcafe */
			for (uint32_t o = 0x100; o < 0x1000; o += 4) {
				uint32_t v;

				if (o >= 0x600 && o < 0x700) {
					continue;
				}
				v = rd(csis + 0x60000 + o);
				if (v && v != 0xdeadcafe && v != 0x80008000 && (v & 0xffff) != 0x00fc) {
					n += snprintf(line + n, sizeof(line) - (size_t)n, " %x:%x", o, v);
				}
				if (n > 200) {
					printf("akita camera: capture: CSIS link 6:%s\n", line);
					n = 0;
				}
			}
			if (n) {
				printf("akita camera: capture: CSIS link 6:%s\n", line);
				n = 0;
			}

			for (unsigned i = 0; i < sizeof(fe_known) / sizeof(fe_known[0]); i++) {
				uint32_t v = rd(fe + fe_known[i]);

				if (v) {
					n += snprintf(line + n, sizeof(line) - (size_t)n, " %x:%x", fe_known[i], v);
				}
				if (n > 200 || (i + 1 == sizeof(fe_known) / sizeof(fe_known[0]) && n)) {
					printf("akita camera: capture: fe known:%s\n", line);
					n = 0;
				}
			}
		}
	}
	/* while streaming: CSIS link 6, the front end's top page, channel 0 (the words that are not 0) */
	{
		static const struct { const char *name; uint32_t pa, len; } dumps[] = {
			{ "CSIS link 6", 0x1c0a0000, 0x100 }, { "CSIS link 6 +0x600", 0x1c0a0600, 0x100 },
			{ "D-PHY 5 clock", 0x1c103100, 0x60 }, { "D-PHY 5 lane 0", 0x1c103200, 0x60 },
			{ "D-PHY 5 lane 3", 0x1c103500, 0x60 }, { "fe +0x20000", 0x1c320000, 0x100 }, { "fe +0x20400", 0x1c320400, 0x100 }, { "fe ch0", 0x1c320500, 0x100 },
		};

		for (unsigned d = 0; d < sizeof(dumps) / sizeof(dumps[0]); d++) {
			vm_offset_t base = dumps[d].pa >= ISPFE_FE_PHYS ? fe + (dumps[d].pa - ISPFE_FE_PHYS) : csis + (dumps[d].pa - ISPFE_CSIS_PHYS);
			char line[512];
			int n = 0;

			for (uint32_t o = 0; o < dumps[d].len && n < (int)sizeof(line) - 24; o += 4) {
				uint32_t v = rd(base + o);

				if (v) {
					n += snprintf(line + n, sizeof(line) - (size_t)n, " +%02x:%x", o, v);
				}
			}
			line[n] = '\0';
			printf("akita camera: capture: streaming: %s:%s\n", dumps[d].name, line);
		}
	}
	{
		vm_offset_t cmu = ml_io_map(CMU_ISPFE_PHYS, 0x4000);
		char line[256];
		int n = 0;

		for (unsigned i = 0; i < sizeof(cmu_ispfe_regs) / sizeof(cmu_ispfe_regs[0]); i++) {
			n += snprintf(line + n, sizeof(line) - (size_t)n, " %x:%x", cmu_ispfe_regs[i], rd(cmu + cmu_ispfe_regs[i]));
			if (n > 200 || i + 1 == sizeof(cmu_ispfe_regs) / sizeof(cmu_ispfe_regs[0])) {
				printf("akita camera: capture: CMU_ISPFE:%s\n", line);
				n = 0;
			}
		}
	}
	delay_for_interval(150, NSEC_PER_MSEC);
	i2c_read16(c->bus, 0x1a, 0x0005, &fc, 1);
	i2c_write16(c->bus, 0x1a, 0x0100, &zero, 1);
	delay(50000);
	printf("akita camera: capture: stream off (frame counter %u); channel 0: enable %#x addr %#x %#x, +0x37904 %#x\n", fc,
	    rd(fe + 0x20540), rd(fe + 0x205c0), rd(fe + 0x205c4), rd(fe + 0x37904));
	wr(fe + 0x20540, 0);
	/* what came: the frame's bytes no longer 0xa5 */
	flush_dcache(frame, FRONT_BUF, FALSE);
	flush_dcache(side, FRONT_SIDE, FALSE);
	for (unsigned i = 0; i < FRONT_BUF; i++) {
		if (((uint8_t *)frame)[i] != 0xa5) {
			changed++;
			first = first == ~0u ? i : first;
		}
	}
	printf("akita camera: capture: %u of %u bytes written (first at %#x); second buffer: %s\n", changed, FRONT_FRAME,
	    first, ((uint8_t *)side)[0] != 0xa5 || ((uint8_t *)side)[4] != 0xa5 ? "written" : "untouched");
	for (unsigned row = 0; row < FRONT_HEIGHT && changed; row += 1024) {
		const uint8_t *b = (const uint8_t *)frame + row * FRONT_STRIDE + 2000;

		printf("akita camera: capture: row %u: %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x\n", row, b[0], b[1], b[2], b[3],
		    b[4], b[5], b[6], b[7], b[8], b[9]);
	}
	{
		vm_offset_t s2 = ml_io_map(0x1c140000ULL, 0x3000);

		printf("akita camera: capture: S2MPU S0 FAULT_STATUS %#x\n", rd(s2 + 0x2000));
	}
down:
	if (fe_clk_set) {
		wr(cmu_top + CMU_TOP_ISPFE_MUX, old_fe_mux);
		delay(10);
		wr(cmu_top + CMU_TOP_ISPFE_DIV, old_fe_div);
	}
	if (mmu_used) {
		ispfe_mmu(false, 0, 0, 0);
	}
	if (sysreg) {
		wr(sysreg + 0x500, rd(sysreg + 0x500) & ~FRONT_DPHY_RESET_BITS);
	}
	cam_smc(SMC_PRIV_REG, PMU_CSI_PHY_ISO, PRIV_REG_WRITE, rd(pmu + 0x1ebc) & ~1u);
	mclk(c->clk, c->clk_bank, c->clk_pin, false);
	pin_out(c->reset_bank, c->reset_pin, false);
	while (on-- > 0) {
		slg_ldo_off(c->ldo[on]);
	}
	printf("akita camera: capture: front camera powered down\n");
}

