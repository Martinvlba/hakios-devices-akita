static bool
i2c_write16(int bus, uint8_t addr, uint16_t reg, const uint8_t *vals, unsigned n)
{
	uint8_t b[8];

	if (n > sizeof(b) - 2) {
		return false;
	}
	b[0] = (uint8_t)(reg >> 8);
	b[1] = (uint8_t)reg;
	memcpy(b + 2, vals, n);
	return i2c_transfer(bus, addr, false, b, 2 + n, true);
}

/* the sensor (powered, out of reset, clocked) set to Android's mode, streamed 2 s with its frame counter read, stopped */
/* the IMX712's mode written (not streaming yet); false if any write failed */
static bool
imx712_mode(const struct sensor *c)
{
	unsigned k = 0, i = 0, failed = 0;

	while (imx712_init[i] != 0) {
		unsigned n = imx712_init[i];
		uint16_t reg = (uint16_t)(imx712_init[i + 1] << 8 | imx712_init[i + 2]);

		if (!i2c_write16(c->bus, 0x1a, reg, &imx712_init[i + 3], n)) {
			failed++;
		}
		i += 3 + n;
		if (++k == 105) {
			delay(20000);           /* (Android's pause after 0x500f) */
		}
	}
	{
		unsigned vt = 0, op = 0;        /* camera_pllvt / camera_pllop: the sensor's PLL multipliers (0x0307, 0x030f)
		                                 * overridden -- a test of whether our sensor runs faster than Android's */

		PE_parse_boot_argn("camera_pllvt", &vt, sizeof(vt));
		PE_parse_boot_argn("camera_pllop", &op, sizeof(op));
		{
			unsigned reg = 0, val = 0;      /* camera_sreg=0xRRRR camera_sval=0xVV: one more sensor register (a test) */

			if (PE_parse_boot_argn("camera_sreg", &reg, sizeof(reg)) && PE_parse_boot_argn("camera_sval", &val, sizeof(val))) {
				uint8_t b = (uint8_t)val, r = 0xee;

				i2c_write16(c->bus, 0x1a, (uint16_t)reg, &b, 1);
				i2c_read16(c->bus, 0x1a, (uint16_t)reg, &r, 1);
				printf("akita camera: %s: sensor %#x = %#x (read %#x)\n", c->name, reg, val, r);
			}
		}
		if (vt) {
			uint8_t b = (uint8_t)vt;

			i2c_write16(c->bus, 0x1a, 0x0307, &b, 1);
		}
		if (op) {
			uint8_t b = (uint8_t)op;

			i2c_write16(c->bus, 0x1a, 0x030f, &b, 1);
		}
	}
	printf("akita camera: %s: the IMX712's mode written (%u registers, %u failed)\n", c->name, k, failed);
	{
		/* read back: EXCK 0x0136/7, PLL 0x0301..0x030f, frame/line length 0x0340..0x0343, link rate 0x0820..0x0823 */
		static const uint16_t rb[] = { 0x0136, 0x0137, 0x0301, 0x0303, 0x0305, 0x0306, 0x0307, 0x030b, 0x030d, 0x030e, 0x030f,
			0x0340, 0x0341, 0x0342, 0x0343, 0x0820, 0x0821, 0x0822, 0x0823, 0x0112, 0x0113, 0x0114, 0x0808, 0x0101 };
		char line[300];
		int n = 0;

		for (unsigned i = 0; i < sizeof(rb) / sizeof(rb[0]); i++) {
			uint8_t v = 0xee;

			i2c_read16(c->bus, 0x1a, rb[i], &v, 1);
			n += snprintf(line + n, sizeof(line) - (size_t)n, " %04x:%02x", rb[i], v);
		}
		printf("akita camera: %s: read back:%s\n", c->name, line);
	}
	return failed == 0;
}

static void
imx712_stream_test(const struct sensor *c)
{
	uint8_t one = 1, zero = 0, fc = 0, last = 0;

	imx712_mode(c);
	delay(7000);
	if (!i2c_write16(c->bus, 0x1a, 0x0100, &one, 1)) {
		printf("akita camera: %s: stream on failed\n", c->name);
		return;
	}
	for (int t = 0; t < 20; t++) {
		delay_for_interval(100, NSEC_PER_MSEC);
		if (i2c_read16(c->bus, 0x1a, 0x0005, &fc, 1)) {
			printf("akita camera: %s: streaming %d ms: frame counter %u%s\n", c->name, (t + 1) * 100, fc,
			    t > 0 && fc != last ? "" : " (not moving)");
			last = fc;
		}
	}
	i2c_write16(c->bus, 0x1a, 0x0100, &zero, 1);
	printf("akita camera: %s: stream off\n", c->name);
}

