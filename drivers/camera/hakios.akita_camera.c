		/* (PMU_ALIVE, 0x15460000-, takes writes only through the secure monitor, as cal-if's pmucal_write_reg() does: a
		 * plain store reset the phone, 11-17 run-cam10) */
		ISTEP("power domain on (PRIV_REG SMC)");
