#define CMU_TOP_PHYS            0x26040000ULL
#define CMU_TOP_CIS_MUX(n)      (0x1010 + 4 * (n))
#define CMU_TOP_CIS_DIV(n)      (0x1810 + 4 * (n))
#define CMU_TOP_CIS_GATE(n)     (0x2038 + 4 * (n))
